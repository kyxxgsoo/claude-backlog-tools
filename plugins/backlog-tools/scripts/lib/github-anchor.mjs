/**
 * GitHub의 헤딩 앵커 계산 — 마크다운 헤딩 텍스트(레벨 표시 `#`를 뗀 나머지)를
 * GitHub이 URL 조각(`#anchor`)으로 바꾸는 규칙을 그대로 흉내 낸다 (ADR-086 ①).
 *
 * 규칙(GitHub 실제 동작 — 비공식이지만 `github-slugger` 등으로 널리 재현됨):
 *   ① 소문자로 바꾼다.
 *   ② 유니코드 문자·숫자·결합기호·공백·하이픈·밑줄만 남기고 나머지 구두점/
 *      기호는 **자리를 메우지 않고 지운다** — 그래서 공백으로 둘러싸인 기호
 *      하나를 지우면 공백 두 개가 남고, 그게 하이픈 두 개짜리 앵커가 된다
 *      (예: "Bourbon & Rye" → "bourbon--rye").
 *   ③ 남은 공백을 전부 하이픈으로 바꾼다 — 연속 공백을 하나로 뭉치지 않는다.
 *
 * 마크다운 인라인 서식(`**볼드**`, `` `코드` ``)은 따로 벗기지 않는다 — 그
 * 구분자(`*`·`` ` ``)도 ②에서 지워지는 구두점이라, 결과가 "렌더링된 평문에서
 * 계산한 것"과 같아진다. 링크(`[글자](url)`)가 헤딩 안에 있으면 이 함수만으로는
 * 맞지 않는다 — 이 레포의 ADR 제목에는 그런 헤딩이 없다.
 *
 * 의존성 없음.
 */
export function githubHeadingAnchor(headingText) {
  return headingText
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\p{M}_\- ]/gu, "")
    .replace(/ /g, "-");
}
